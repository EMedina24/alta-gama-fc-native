/**
 * Regenerates `src/app/_debug/stats-fixtures.ts` from the captured production
 * payloads in `scripts/fixtures/stats-*.json`.
 *
 *   node scripts/gen-stats-fixtures.mjs
 *
 * ⚠⚠ **This exists because the file it writes says "GENERATED" and, until
 * 2026-09-10, nothing generated it.** The header forbids hand-editing the
 * literals — trap 48: a `_debug` sample that invents a field turns a red test
 * green and the doc comments on both sides then agree with the bug — but with
 * no generator the only way to refresh them WAS to hand-edit. The merged-block
 * work (ADR 0149) needed five new blocks pulled out of four payloads, which is
 * exactly the moment that gap would have bitten.
 *
 * To refresh: re-capture the four payloads, then run this.
 *
 *   curl -sf https://crono-gol.com/cronogol/players/valverde-1/stats \
 *     -o scripts/fixtures/stats-player-valverde.json
 *   curl -sf https://crono-gol.com/cronogol/players/raphinha/stats \
 *     -o scripts/fixtures/stats-player-raphinha.json
 *   curl -sf https://crono-gol.com/cronogol/teams/barcelona/stats \
 *     -o scripts/fixtures/stats-team-barcelona.json
 *   curl -sf https://crono-gol.com/cronogol/teams/fc-bayern-muenchen/stats \
 *     -o scripts/fixtures/stats-team-bayern.json
 *
 * ⚠ Bayern's slug is `fc-bayern-muenchen`, not `bayern-munich`.
 *
 * ⚠ Every block below is SELECTED by season and competition, never by index —
 * `seasons[0]` is a different block depending on arrival order, which the
 * backend only started guaranteeing on 2026-09-10.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SEASON = 2026;

const read = (name) =>
  JSON.parse(readFileSync(resolve(root, 'scripts/fixtures', name), 'utf8'));

const barca = read('stats-team-barcelona.json');
const bayern = read('stats-team-bayern.json');
const raphinha = read('stats-player-raphinha.json');
const valverde = read('stats-player-valverde.json');

/** A `seasons[]` row, by season AND competition. Throws rather than guessing. */
function block(payload, competition, label) {
  const found = payload.seasons.find(
    (s) => s.season === SEASON && s.competition === competition,
  );
  if (!found) throw new Error(`${label}: no ${SEASON} ${competition} block`);
  return found;
}

/** A `seasonTotals[]` row, by season. */
function totals(payload, label) {
  const found = (payload.seasonTotals ?? []).find((s) => s.season === SEASON);
  if (!found) {
    throw new Error(
      `${label}: no ${SEASON} seasonTotals block — the payload predates ` +
        `senpai-backend §120.15 (2026-09-10). Re-capture it.`,
    );
  }
  return found;
}

/* ── Emitting ────────────────────────────────────────────────────────────── */

/** An object key: bare where it is an identifier, quoted where it is not. */
const key = (k) => (/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(k) ? k : JSON.stringify(k));

/**
 * TS source for one value, at `depth` levels of two-space indent.
 *
 * ⚠ Strings go through `JSON.stringify`, so a club name with an accent or a
 * quote in it cannot break the file.
 */
function emit(value, depth) {
  const pad = '  '.repeat(depth);
  const inner = '  '.repeat(depth + 1);
  if (value === null) return 'null';
  if (Array.isArray(value)) {
    if (value.length === 0) return '[]';
    const items = value.map((v) => `${inner}${emit(v, depth + 1)},`).join('\n');
    return `[\n${items}\n${pad}]`;
  }
  if (typeof value === 'object') {
    const entries = Object.entries(value);
    if (entries.length === 0) return '{}';
    const items = entries
      .map(([k, v]) => `${inner}${key(k)}: ${emit(v, depth + 1)},`)
      .join('\n');
    return `{\n${items}\n${pad}}`;
  }
  return JSON.stringify(value);
}

const constant = (name, type, value, note) =>
  `${note}export const ${name}: ${type} = ${emit(value, 0)};\n`;

const HEADER = `/**
 * Real Season stats payloads, for \`/_debug/stats\` (ADR 0141, ADR 0149).
 *
 * ⚠⚠ **GENERATED by \`scripts/gen-stats-fixtures.mjs\` from
 * \`scripts/fixtures/stats-*.json\`, which are themselves production responses
 * captured from \`crono-gol.com\`. Not one value here was typed by hand.** Trap 48
 * is exactly this file's failure mode: a \`_debug\` sample that invents a field
 * turns a red test green, and the doc comments on both sides then agree with the
 * bug. If these need refreshing, re-capture the JSON and re-run the generator —
 * do not edit the literals.
 *
 * The per-competition blocks, and what each one is for:
 *
 * - \`CLUB_FULL\` — Barcelona, LaLiga ${SEASON}. Every card draws. ⚠ Its \`timeline\`
 *   runs \`mw 2, 1, 3, 4\`: a real postponement, and the reason the cumulative
 *   line is plotted on the array index.
 * - \`CLUB_THIN\` — Barcelona, Champions League ${SEASON}. \`coverage.sufficient\` is
 *   false at \`ratio: 1\` — a minimum-fixtures floor — so every event field is
 *   null while the scoreline block is complete.
 * - \`CLUB_SCORELINES_ONLY\` — Bayern, Bundesliga ${SEASON}. The permanent case: that
 *   source writes no events at all, so the goals chart is the only chart, and
 *   two matches played is what a real September looks like.
 * - \`PLAYER_FULL\` / \`PLAYER_THIN\` — Raphinha's two ${SEASON} blocks. ⚠ The thin one
 *   still answers \`yellows: 0, braces: 0\` rather than nulls, which is why the
 *   player view gates its counts on coverage rather than on the type.
 * - \`PLAYER_GOALLESS\` — Valverde's LaLiga ${SEASON} block, \`goals: 0\`. ⚠ The
 *   screen from Ed's TestFlight report, and the reason ADR 0148 exists: every
 *   goal-derived chart is suppressed here.
 *
 * And the MERGED blocks the headline figures read (ADR 0149):
 *
 * - \`CLUB_TOTALS\` — Barcelona's merged ${SEASON}: LaLiga + Champions League,
 *   \`goalsFor\` 22 against the LaLiga block's 17. ⚠⚠ Its \`timeline\` reads
 *   \`mw [2, 1, 3, 4, 1]\` — TWO fixtures labelled matchday 1, in two different
 *   competitions. That is the case that proves a merged timeline may not be
 *   grouped or labelled by \`mw\`.
 * - \`CLUB_TOTALS_SINGLE\` — Bayern's merged ${SEASON}, \`competitions\` of length 1.
 *   ⚠ It IS the Bundesliga block, so nothing may label it "all competitions".
 * - \`PLAYER_TOTALS\` — Raphinha's merged ${SEASON}: 8 goals against the LaLiga
 *   block's 6.
 * - \`PLAYER_TOTALS_GOALLESS\` — ⚠⚠ **the acceptance case.** Valverde's merged
 *   ${SEASON} reads \`goals: 1\` where \`PLAYER_GOALLESS\` reads \`0\`. Pair them and
 *   the whole of 0149 is on one screen: the headline is right, the charts stay
 *   suppressed because the LaLiga block they read really is goalless, and
 *   \`coverage.sufficient\` is false at \`ratio: 1\`.
 */
import type {
  PlayerSeasonStatsView,
  PlayerSeasonTotalsView,
  TeamSeasonStatsView,
  TeamSeasonTotalsView,
} from '@/lib/cronogol/types';

`;

