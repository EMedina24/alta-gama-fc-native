console.log(`wrote ${out}`);

/* ⚠ Guards, not decoration: each one is a property the debug screen and the
 * harness rely on, asserted here so a re-capture that changes the data fails
 * loudly rather than quietly redefining what a "thin" block means. */
const checks = [
  [block(barca, 'laliga', 'barca').coverage.sufficient === true, 'CLUB_FULL is swept'],
  [
    block(barca, 'champions-league', 'barca').coverage.sufficient === false,
    'CLUB_THIN is below the floor',
  ],
  [
    block(bayern, 'bundesliga', 'bayern').yellows === null,
    'CLUB_SCORELINES_ONLY writes no events',
  ],
  [block(valverde, 'laliga', 'valverde').goals === 0, 'PLAYER_GOALLESS really is 0'],
  [totals(valverde, 'valverde').goals === 1, 'and its merged block really is 1'],
  [
    totals(barca, 'barca').competitions.length > 1,
    'CLUB_TOTALS spans more than one competition',
  ],
  [
    totals(bayern, 'bayern').competitions.length === 1,
    'CLUB_TOTALS_SINGLE spans exactly one',
  ],
  [
    totals(barca, 'barca').timeline.filter((e) => e.mw === 1).length === 2,
    'CLUB_TOTALS carries two matchday-1 fixtures',
  ],
  [
    totals(barca, 'barca').home.played + totals(barca, 'barca').away.played ===
      totals(barca, 'barca').timeline.length,
    'the merged venue split accounts for every merged fixture',
  ],
];
let failed = 0;
for (const [ok, what] of checks) {
  if (!ok) {
    console.error(`  ✗ ${what}`);
    failed += 1;
  }
}
if (failed > 0) {
  console.error(`\n${failed} guard(s) failed — the captured data has changed shape.`);
  process.exit(1);
}
console.log(`${checks.length} guards passed`);
